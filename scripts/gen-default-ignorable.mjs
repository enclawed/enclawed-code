#!/usr/bin/env node
// Generates src/unicode-ignorable.mjs: the Unicode Default_Ignorable_Code_Point
// property as a sorted table of inclusive ranges.
//
// Source: Unicode Character Database, DerivedCoreProperties.txt, property
// Default_Ignorable_Code_Point (https://www.unicode.org/Public/UCD/latest/ucd/DerivedCoreProperties.txt;
// definition in UAX #44 and The Unicode Standard section 5.21). The values are
// read from the ICU tables built into this Node runtime through the regular
// expression property escape \p{Default_Ignorable_Code_Point}, so the Unicode
// and ICU versions recorded in the output are exactly the data used.
//
//   node scripts/gen-default-ignorable.mjs          rewrite the table
//   node scripts/gen-default-ignorable.mjs --check  exit 1 if the table is stale
import fs from "node:fs";

const re = /\p{Default_Ignorable_Code_Point}/u;
const ranges = [];
let start = -1;
for (let cp = 0; cp <= 0x110000; cp++) {
  const hit = cp < 0x110000 && !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCodePoint(cp));
  if (hit && start < 0) {
    start = cp;
  } else if (!hit && start >= 0) {
    ranges.push([start, cp - 1]);
    start = -1;
  }
}
const hex = (n) => `0x${n.toString(16).toUpperCase().padStart(4, "0")}`;
const body = `// GENERATED by scripts/gen-default-ignorable.mjs. Do not edit by hand.
//
// Unicode Default_Ignorable_Code_Point (DerivedCoreProperties.txt), Unicode
// ${process.versions.unicode} as shipped in ICU ${process.versions.icu} (Node ${process.version}).
// https://www.unicode.org/Public/UCD/latest/ucd/DerivedCoreProperties.txt
// These code points render as nothing when unsupported (UAX #44, The Unicode
// Standard section 5.21), so a person reading the text cannot see them.

export const UNICODE_VERSION = ${JSON.stringify(process.versions.unicode)};

/** Inclusive [first, last] ranges, sorted. */
export const DEFAULT_IGNORABLE_RANGES = [
${ranges.map(([a, b]) => `  [${hex(a)}, ${hex(b)}],`).join("\n")}
];
`;
const target = new URL("../src/unicode-ignorable.mjs", import.meta.url);
if (process.argv.includes("--check")) {
  // Compare the ranges only: a newer runtime with the same data is not stale.
  const { DEFAULT_IGNORABLE_RANGES } = await import(target.href);
  if (JSON.stringify(DEFAULT_IGNORABLE_RANGES) !== JSON.stringify(ranges)) {
    console.error(`src/unicode-ignorable.mjs differs from Unicode ${process.versions.unicode}: run node scripts/gen-default-ignorable.mjs`);
    process.exit(1);
  }
  process.exit(0);
}
fs.writeFileSync(target, body);
console.log(`wrote ${ranges.length} ranges (Unicode ${process.versions.unicode})`);
